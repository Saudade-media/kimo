/**
 * Board 42 rules "Secret · Automatic" and "Secret storage": the create secret Kimo generates
 * (32 random bytes), how it shows on screen (masked; Show reveals it for 30 s) and where it is
 * kept (OS keychain on desktop, browser storage on web; never in links, .kimo files or logs).
 */

/** Random bytes in an Automatic secret. */
export const SECRET_BYTES = 32

/** Show hides the value again after this long (Settings closing hides it too). */
export const SECRET_REVEAL_MS = 30_000

/** Prefix of an Automatic secret, so a pasted value is recognisable as Kimo's. */
export const SECRET_PREFIX = "kimo_cs_"

/** The bullets a masked secret shows in a command or variables block (13, as on the board). */
export const MASK = "•".repeat(13)

/** The bullets a masked Custom field shows (24, as on the board). */
export const FIELD_MASK = "•".repeat(24)

function base64Url(bytes: Uint8Array): string {
  let s = ""
  for (const b of bytes) s += String.fromCharCode(b)
  return btoa(s).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "")
}

/** A new Automatic secret: `kimo_cs_` and 32 random bytes in base64url (43 characters). */
export function generateSecret(
  random: (bytes: Uint8Array) => Uint8Array = (b) => crypto.getRandomValues(b),
): string {
  return `${SECRET_PREFIX}${base64Url(random(new Uint8Array(SECRET_BYTES)))}`
}

/** How a secret is stored: generated by Kimo, typed by the person, or none (an open relay). */
export type SecretMode = "auto" | "custom" | "none"

export interface RevealTimers {
  setTimeout(fn: () => void, ms: number): unknown
  clearTimeout(handle: unknown): void
}

/**
 * Show / Hide of a secret: `reveal()` shows it and hides it again after {@link SECRET_REVEAL_MS}
 * (a second Show restarts the 30 s), `hide()` at once (Hide, Settings closing).
 */
export class SecretReveal {
  private handle: unknown = null
  private shown = false
  private readonly listeners = new Set<() => void>()

  constructor(
    private readonly timers: RevealTimers,
    private readonly ms = SECRET_REVEAL_MS,
  ) {}

  get visible(): boolean {
    return this.shown
  }

  subscribe(listener: () => void): () => void {
    this.listeners.add(listener)
    return () => this.listeners.delete(listener)
  }

  reveal(): void {
    if (this.handle !== null) this.timers.clearTimeout(this.handle)
    this.handle = this.timers.setTimeout(() => {
      this.handle = null
      this.set(false)
    }, this.ms)
    this.set(true)
  }

  hide(): void {
    if (this.handle !== null) this.timers.clearTimeout(this.handle)
    this.handle = null
    this.set(false)
  }

  dispose(): void {
    this.hide()
    this.listeners.clear()
  }

  private set(shown: boolean) {
    if (this.shown === shown) return
    this.shown = shown
    for (const l of [...this.listeners]) l()
  }
}

// --- Storage -------------------------------------------------------------------------------------

/** Keychain service and account (desktop): `kimo` / `relay.secret`, shown as kimo.relay.secret. */
export const RELAY_SECRET_SERVICE = "kimo"
export const RELAY_SECRET_ACCOUNT = "relay.secret"
/** Browser storage key (web): this origin only. */
export const WEB_RELAY_SECRET_KEY = "kimo.relay.secret"

export interface RelaySecretStore {
  readonly backend: "keychain" | "browser" | "memory"
  get(): Promise<string | null>
  set(value: string): Promise<void>
  delete(): Promise<void>
}

/** `localStorage`-like store (injected so tests need no DOM). */
export interface KeyValue {
  getItem(key: string): string | null
  setItem(key: string, value: string): void
  removeItem(key: string): void
}

export function createWebSecretStore(storage: KeyValue | null): RelaySecretStore {
  return {
    backend: "browser",
    get: async () => {
      try {
        return storage?.getItem(WEB_RELAY_SECRET_KEY) || null
      } catch {
        return null
      }
    },
    set: async (value) => {
      storage?.setItem(WEB_RELAY_SECRET_KEY, value)
    },
    delete: async () => {
      storage?.removeItem(WEB_RELAY_SECRET_KEY)
    },
  }
}

export type Invoke = (cmd: string, args?: Record<string, unknown>) => Promise<unknown>

/** Desktop: the OS keychain through `kimo_relay_secret_*` (Rust, `keyring`). */
export function createKeychainSecretStore(invoke: Invoke): RelaySecretStore {
  return {
    backend: "keychain",
    get: async () => ((await invoke("kimo_relay_secret_get")) as string | null) ?? null,
    set: async (value) => {
      await invoke("kimo_relay_secret_set", { value })
    },
    delete: async () => {
      await invoke("kimo_relay_secret_delete")
    },
  }
}

export function createMemorySecretStore(initial: string | null = null): RelaySecretStore {
  let value = initial
  return {
    backend: "memory",
    get: async () => value,
    set: async (v) => {
      value = v
    },
    delete: async () => {
      value = null
    },
  }
}
