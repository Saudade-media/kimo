const kinds = (line: string, lang: Parameters<typeof tokenizeInk>[1]) =>
  tokenizeInk(line, lang).map((t) => [t.kind, t.text])

describe("§ 1 Ink tokens match the designed lines", () => {
  test("Line 1 / 3 / 5 / 13 of (a) React + Tailwind", () => {
    // ebU7B "export function " strong · vyKlA "Hero" plain · PCwwp "() {" punct
    expect(kinds("export function Hero() {", "jsx")).toEqual([
      ["strong", "export"],
      ["plain", " "],
      ["strong", "function"],
      ["plain", " Hero"],
      ["punct", "()"],
      ["plain", " "],
      ["punct", "{"],
    ])
    // ChpnH "    <" punct · Ny3iu "section" strong · className attr · "=" punct · string plain
    expect(kinds('    <section className="flex flex-col">', "jsx")).toEqual([
      ["plain", "    "],
      ["punct", "<"],
      ["strong", "section"],
      ["plain", " "],
      ["attr", "className"],
      ["punct", "="],
      ["plain", '"flex flex-col"'],
      ["punct", ">"],
    ])
    // Text content stays one primary token (SNbh7 "Plan less. Ship more together.").
    expect(kinds("        Plan less. Ship more together.", "jsx")).toEqual([
      ["plain", "        Plan less. Ship more together."],
    ])
    // Line 13: "{" punct · comment italic · "}" punct.
    expect(kinds("      {/* instance → component import */}", "jsx")).toEqual([
      ["plain", "      "],
      ["punct", "{"],
      ["comment", "/* instance → component import */"],
      ["punct", "}"],
    ])
  })
  test("(b) HTML comment line and (c) DTCG JSON keys", () => {
    expect(kinds("<!-- generated by Kimo · Home — Desktop -->", "jsx")).toEqual([
      ["comment", "<!-- generated by Kimo · Home — Desktop -->"],
    ])
    // t17HO "color" strong + ": {" punct; nWzSI "$type" attr, value plain, "," punct.
    expect(kinds('  "color": {', "json")).toEqual([
      ["plain", "  "],
      ["strong", '"color"'],
      ["punct", ":"],
      ["plain", " "],
      ["punct", "{"],
    ])
    expect(kinds('      "$type": "color",', "json")).toEqual([
      ["plain", "      "],
      ["attr", '"$type"'],
      ["punct", ":"],
      ["plain", ' "color"'],
      ["punct", ","],
    ])
  })
  test("css: selector strong, property attr, block comments across lines", () => {
    expect(kinds(".k-hero {", "css")).toEqual([
      ["strong", ".k-hero "],
      ["punct", "{"],
    ])
    expect(kinds("  color: var(--ink);", "css")).toEqual([
      ["plain", "  "],
      ["attr", "color"],
      ["punct", ":"],
      ["plain", " var"],
      ["punct", "("],
      ["plain", "--ink"],
      ["punct", ");"],
    ])
    const lines = inkLines(["/* a", "b */ .x {"], "css")
    expect(lines[0]).toEqual([{ kind: "comment", text: "/* a" }])
    expect(lines[1]?.[0]).toEqual({ kind: "comment", text: "b */" })
  })
})

describe("§ 1 roots and highlight", () => {
  const parents: Record<string, string | null> = {
    hero: null,
    headline: "hero",
    button: "hero",
    label: "button",
    other: null,
  }
  const inside = insideBy((id) => parents[id] ?? null)
  test("top-most selected nodes are the roots", () => {
    expect(resolveTarget(["hero"], [], inside)).toEqual({ roots: ["hero"], highlight: [] })
    expect(resolveTarget(["hero", "headline"], [], inside)).toEqual({
      roots: ["hero"],
      highlight: ["headline"],
    })
  })
  test("selecting a child keeps the root and highlights it (vignette a)", () => {
    expect(resolveTarget(["headline"], ["hero"], inside)).toEqual({
      roots: ["hero"],
      highlight: ["headline"],
    })
    expect(resolveTarget(["label"], ["hero"], inside).roots).toEqual(["hero"])
    // Leaving the subtree retargets.
    expect(resolveTarget(["other"], ["hero"], inside)).toEqual({ roots: ["other"], highlight: [] })
    expect(resolveTarget([], ["hero"], inside)).toEqual({ roots: [], highlight: [] })
  })
  test("instance-owned ids nest by their IdPath", () => {
    const by = insideBy(() => null)
    expect(by("inst/a/b", "inst")).toBe(true)
    expect(by("inst/a/b", "inst/a")).toBe(true)
    expect(by("inst", "inst/a")).toBe(false)
  })
})

describe("§ 1 source map on real exporter output", () => {
  test("React: the root spans its markup, children their lines; clicking selects the innermost", async () => {
    const g = await generateCode({ document: () => doc }, ["Matrix0001"], "react", DEFAULT_TOGGLES)
    expect(g.errors).toEqual([])
    const root = g.files[0]
    expect(root?.path).toBe("Matrix.tsx")
    const map = root?.map ?? null
    expect(map?.get("Matrix0001")).toEqual({ start: 4, end: 40 })
    expect(map?.get("RowFrame01")).toEqual({ start: 5, end: 11 })
    expect(map?.get("RowKid0001")).toEqual({ start: 6, end: 6 })
    // The shown file carries no ids (same output as Export).
    expect(root?.contents).not.toContain("data-kimo-id")
    expect([...highlightedLines(map, ["RowFrame01"])]).toEqual([5, 6, 7, 8, 9, 10, 11])
    expect(nodeAtLine(map, 6)).toBe("RowKid0001")
    expect(nodeAtLine(map, 5)).toBe("RowFrame01")
    expect(nodeAtLine(map, 1)).toBe(null)
  })
  test("HTML: index.html first, mapped; CSS files unmapped", async () => {
    const g = await generateCode({ document: () => doc }, ["Matrix0001"], "html", DEFAULT_TOGGLES)
    expect(g.files.map((f) => f.path)).toEqual(["index.html", "styles.css", "tokens.css"])
    expect(g.files[0]?.map?.has("RowKid0001")).toBe(true)
    expect(g.files[1]?.map).toBe(null)
  })
  test("mismatched line counts give no map", () => {
    expect(sourceMapOf("a\nb", "a")).toBe(null)
  })
  test("tokens: DTCG first, only the variables the selection uses", async () => {
    const g = await generateCode({ document: () => doc }, ["Matrix0001"], "tokens", DEFAULT_TOGGLES)
    expect(g.files.map((f) => f.path)).toEqual(["tokens.json", "tokens.css"])
    expect(g.tokens).toEqual({ used: 2, total: 2 })
    expect(JSON.parse(g.files[0]?.contents ?? "{}")).toBeTruthy()
  })
  test("usedVariables keeps alias targets", () => {
    const v = (name: string, value: unknown, used: boolean) =>
      ({
        name,
        type: "color",
        css: name,
        value,
        entries: null,
        resolved: null,
        usage: used ? ["fill"] : [],
      }) as never
    const out = usedVariables([
      v("a", { $ref: "b" }, true),
      v("b", "#fff", false),
      v("c", "#000", false),
    ])
    expect(out.map((x: { name: string }) => x.name)).toEqual(["a", "b"])
  })
})

describe("§ 1 copy, truncation, memory", () => {
  test("panel copy", () => {
    expect(linesMeta(19)).toBe("19 lines")
    expect(linesMeta(2318)).toBe("2,318 lines")
    expect(tokensMeta(4, 31)).toBe("4 used · 31 total")
    expect(truncatedTitle(2318)).toBe("Showing 400 of 2,318 lines")
    expect(copyAllLabel(2318)).toBe("Copy all 2,318 lines")
    expect(liveStatus(false)).toBe("Live · updates as you edit")
    expect(liveStatus(true)).toBe("Live · paused while > 400 lines")
    expect(unsupportedTitle("Prompt")).toBe("Prompt nodes have no code")
    expect(CODE_TAB_MAX_LINES).toBe(400)
  })
  test("mixed selection: one-line comment per skipped node (c3YQH)", () => {
    expect(skippedComment("Pricing.tsx", "Prompt", "Pricing brief")).toBe(
      "{/* skipped: Prompt “Pricing brief” */}",
    )
    expect(skippedComment("index.html", "Note", "Gui · note")).toBe(
      "<!-- skipped: Note “Gui · note” -->",
    )
    expect(skippedComment("tokens.json", "Note", "x")).toBe(null)
  })
  test("framework remembered per file, default React + Tailwind", () => {
    const m = new Map<string, string>()
    const storage = {
      getItem: (k: string) => m.get(k) ?? null,
      setItem: (k: string, v: string) => void m.set(k, v),
    }
    expect(readFramework("a", storage)).toBe("react")
    writeFramework("a", "tokens", storage)
    expect(readFramework("a", storage)).toBe("tokens")
    expect(readFramework("b", storage)).toBe("react")
  })
  test("CodeLine renders the highlighted variant", () => {
    const html = renderToString(
      h(CodeLine, { number: 5, tokens: [{ kind: "strong", text: "h1" }], highlighted: true }),
    )
    expect(html).toContain("kimo-code-line--highlighted")
    expect(html).toContain("kimo-code-line__token--strong")
  })
})

describe("§ 2 review step", () => {
  test("unified diff: 3 lines of context, numbers per side, hunks split", () => {
    const before = Array.from({ length: 20 }, (_, i) => `l${i + 1}`)
    const after = [...before]
    after[3] = "L4"
    after[16] = "L17"
    const d = unifiedDiff(`${before.join("\n")}\n`, `${after.join("\n")}\n`)
    expect(d.added).toBe(2)
    expect(d.removed).toBe(2)
    expect(d.hunks.length).toBe(2)
    expect(d.hunks[0]?.rows.map((r) => `${r.kind[0]}${r.number}`)).toEqual([
      "c1",
      "c2",
      "c3",
      "r4",
      "a4",
      "c5",
      "c6",
      "c7",
    ])
    expect(unifiedDiff("a\n", "a\n").hunks).toEqual([])
    expect(unifiedDiff("", "x\ny\n").added).toBe(2)
  })
  test("defaults: Overwrite only for files Kimo wrote last time and nobody touched", () => {
    const disk = new TextEncoder().encode("old")
    expect(defaultChoice(disk, contentHash("old"))).toBe("overwrite")
    expect(defaultChoice(disk, contentHash("other"))).toBe("keep")
    expect(defaultChoice(disk, undefined)).toBe("keep")
  })
  test("review copy", () => {
    expect(reviewDesc(2, 3, "~/loom/src/components")).toBe(
      "2 of 3 files already exist in ~/loom/src/components",
    )
    expect(reviewSummary(1, 1, 1)).toBe("1 overwrite · 1 kept · 1 new")
    expect(writeLabel(2)).toBe("Write 2 files")
  })
  test("planWrite keeps what is on disk for changed files", async () => {
    const platform = createMemoryPlatform({ files: { "/out/a.css": "old" } })
    const plan = await planWrite([{ path: "a.css", contents: "new" }], "/out", platform)
    expect(new TextDecoder().decode(plan[0]?.existing)).toBe("old")
  })
  test("ReviewFileRow: changed (Keep | Overwrite) and new (badge)", () => {
    const changed = renderToString(
      h(ReviewFileRow, {
        name: "Hero.tsx",
        kind: "changed",
        added: 12,
        removed: 4,
        choice: "overwrite",
        selected: true,
      }),
    )
    for (const s of [
      "+12",
      "−4",
      "changed on disk",
      "Keep",
      "Overwrite",
      "kimo-review-row--selected",
    ])
      expect(changed).toContain(s)
    const fresh = renderToString(h(ReviewFileRow, { name: "tokens.css", kind: "new" }))
    expect(fresh).toContain("new file")
    expect(fresh).toContain("kimo-review-row__new")
  })
})

describe("§ 2 progress, error, toast, PNG", () => {
  test("progress / retry copy and status rows", () => {
    expect(progressLabel(2, 3, "/Users/me/loom/src/components")).toBe(
      "Writing 2 of 3 · ~/loom/src/components",
    )
    expect(retryLabel(2)).toBe("Retry 2 files")
    const row = renderToString(h(FileStatusRow, { name: "Button.tsx", status: "writing" }))
    expect(row).toContain("writing…")
    expect(row).toContain("lucide-loader-circle")
  })
  test("write errors name the file, the OS error and what landed", () => {
    const e = describeWriteError(
      { code: "PERMISSION", errno: "EACCES" },
      "Button.tsx",
      "/Users/me/loom/src/components",
      ["Hero.tsx"],
      ["tokens.css"],
    )
    expect(e.title).toBe("Couldn't write Button.tsx")
    expect(e.description).toBe(
      "Permission denied (EACCES). ~/loom/src/components is read-only. Hero.tsx was written; tokens.css was not started.",
    )
    expect(describeWriteError({ errno: "ENOSPC" }, "a", "/x", [], []).description).toContain(
      "Disk full (ENOSPC)",
    )
  })
  test("toasts (pQlt5)", () => {
    const folder = "/Users/me/loom/src/components"
    expect(exportToastOf({ kind: "folder", folder, written: ["a", "b", "c"], kept: [] })).toEqual({
      tone: "success",
      icon: "circle-check",
      text: "Exported 3 files to ~/loom/src/components",
      reveal: folder,
      duration: 4000,
    })
    expect(exportToastOf({ kind: "zip", name: "kimo-export-hero.zip" }).text).toBe(
      "Downloaded kimo-export-hero.zip",
    )
    expect(exportToastOf({ kind: "zip", name: "x.zip" }).reveal).toBe(null)
    expect(exportToastOf({ kind: "folder", folder, written: ["a", "b"], kept: ["c"] }).text).toBe(
      "2 written · 1 kept as-is",
    )
    const c = exportToastOf({
      kind: "folder",
      folder,
      written: ["a"],
      kept: [],
      cancelled: { total: 3 },
    })
    expect([c.tone, c.icon, c.text, c.duration]).toEqual([
      "warning",
      "circle-alert",
      "Export cancelled · 1 of 3 written",
      6000,
    ])
  })
  test("PNG size line", () => {
    expect(pngSizeLine(720, 366, 2, 212 * 1024)).toBe("720 × 366 → 1440 × 732 · ≈ 212 KB")
  })
})
