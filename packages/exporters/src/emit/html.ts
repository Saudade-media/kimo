/**
 * HTML + CSS emitter: semantic-ish static markup with one class per node (`.k-<key>`), a
 * stylesheet in document order, and `tokens.css` with CSS custom properties per variable and
 * theme-axis selectors (`[data-mode="dark"]`). Instances are always expanded.
 */
import { CssWriter, type Decl } from "../css/style"
import type { IRDocument, IRNode } from "../ir/types"
import { el, toHtml } from "./el"
import { Markup } from "./markup"
import type { IconLookup } from "./svgpaint"
import { emitTokensCss } from "./tokens"
import type { ExportFile } from "./types"

export interface HtmlOptions {
  /** Variables as CSS custom properties (board 07 option; default true). */
  variables?: boolean
  /** Keep layer names as `data-layer` attributes (board 07 option; default true). */
  layerNames?: boolean
  /** Add `data-kimo-id` attributes (verification). Default false. */
  ids?: boolean
  /** Loaded icon glyphs (see `loadIcons`). */
  icons?: IconLookup
  /** Class prefix. Default `k-`. */
  classPrefix?: string
  /** Extra CSS appended to `styles.css` (e.g. `@font-face` rules). */
  extraCss?: string
}

/** The reset every exported page relies on (the canvas has no margins or borders). */
export const BASE_CSS = `*, ::before, ::after { box-sizing: border-box; margin: 0; padding: 0; border: 0 solid; }
svg { display: block; }
body { -webkit-font-smoothing: antialiased; }`

function rule(selector: string, decls: Decl[]): string {
  if (decls.length === 0) return ""
  return `${selector} {\n${decls.map((d) => `  ${d.prop}: ${d.value};`).join("\n")}\n}`
}

/** Emits `index.html`, `styles.css` and (with variables) `tokens.css`. */
export function emitHtml(ir: IRDocument, options: HtmlOptions = {}): ExportFile[] {
  const variables = options.variables !== false
  const prefix = options.classPrefix ?? "k-"
  const rules: string[] = []
  const writer = new CssWriter({
    variables,
    onIssue: (code, message, nodeId) =>
      ir.issues.push({ code, message, ...(nodeId ? { nodeId } : {}) }),
  })
  const axisAttr = new Map(ir.axes.map((a) => [a.key, a.attr]))
  const markup = new Markup(
    {
      writer,
      icons: options.icons,
      layerNames: options.layerNames !== false,
      ids: options.ids === true,
      styleAttrs(node: IRNode, css) {
        const cls = `${prefix}${node.key}`
        rules.push(rule(`.${cls}`, [...css.placement, ...css.own]))
        if (css.after) rules.push(rule(`.${cls}::after`, css.after))
        return [["class", cls]]
      },
      runAttrs(node, i, decls) {
        const cls = `${prefix}${node.key}-r${i + 1}`
        rules.push(rule(`.${cls}`, decls))
        return [["class", cls]]
      },
      onIssue: (code, message, nodeId) =>
        ir.issues.push({ code, message, ...(nodeId ? { nodeId } : {}) }),
    },
    (k) => axisAttr.get(k) ?? `data-${k}`,
  )
  const bodies = ir.roots.map((r) => toHtml(markup.build(r), 2))
  const head = [
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    `<title>${ir.name.replace(/[<&]/g, "")}</title>`,
    ...(variables ? ['<link rel="stylesheet" href="tokens.css">'] : []),
    '<link rel="stylesheet" href="styles.css">',
  ]
  const html = [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    ...head.map((l) => `  ${l}`),
    "</head>",
    "<body>",
    ...bodies,
    "</body>",
    "</html>",
    "",
  ].join("\n")
  const css = [
    "/* Generated by Kimo (@kimo/exporters). Do not edit. */",
    BASE_CSS,
    ...rules.filter(Boolean),
    ...(options.extraCss ? [options.extraCss] : []),
  ].join("\n\n")
  const files: ExportFile[] = [
    { path: "index.html", contents: html },
    { path: "styles.css", contents: `${css}\n` },
  ]
  if (variables) files.push({ path: "tokens.css", contents: emitTokensCss(ir) })
  void el
  return files
}
