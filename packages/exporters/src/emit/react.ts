/**
 * React + Tailwind v4 emitter (teardown §12 M7): one file per exported root (page) and, with
 * "split instances into components", one file per component with typed props generated from
 * the component's declared props (§9.6) — text → `string`, boolean → `boolean` (conditional
 * render), enum → a union of option names (per-option classes), instance → `ReactNode`, slot →
 * `children` (one slot) or a named `ReactNode` prop. Everything else is inlined: an instance
 * whose overrides no declared prop expresses is emitted expanded. `tokens.css` holds the CSS
 * variables and the `@theme inline` block; utilities use theme tokens where a value is bound.
 *
 * Where a component sits in its parent (position, flex item sizing) is the caller's: a
 * component root takes those utilities through `className` (its authored size is the default).
 */
import { CssWriter, type Decl, type NodeCss } from "../css/style"
import { type ThemeTokens, utilities } from "../css/tailwind"
import { kebab } from "../ir/names"
import type { IRComponent, IRComponentProp, IRDocument, IRNode } from "../ir/types"
import { type AttrValue, type Child, el, isEl, toJsx } from "./el"
import { Markup } from "./markup"
import type { IconLookup } from "./svgpaint"
import { emitTailwindTheme, emitTokensCss, tailwindNamespaces, tailwindSuffix } from "./tokens"
import type { ExportFile } from "./types"

export interface ReactOptions {
  /** Variables as CSS custom properties / theme tokens (default true). */
  variables?: boolean
  /** Split instances into components (default true; needs `buildIR({ components: true })`). */
  components?: boolean
  /** Keep layer names as `data-layer` attributes (default false for React). */
  layerNames?: boolean
  /** `data-kimo-id` attributes (verification). */
  ids?: boolean
  icons?: IconLookup
}

/** `[attribute: \`data-${string}\`]` (theme attributes pass through to the root). */
const DATA_ATTRIBUTES = ["  [attribute: `data-$", "{string}`]: string | undefined"].join("")
const HEADER = "/* Generated by Kimo (@kimo/exporters). Do not edit. */"
const SIZE_PROPS = new Set([
  "width",
  "height",
  "min-width",
  "min-height",
  "max-width",
  "max-height",
])

/** Emits `<Root>.tsx` per root, `<Component>.tsx` per component and `tokens.css`. */
export function emitReact(ir: IRDocument, options: ReactOptions = {}): ExportFile[] {
  return new ReactEmitter(ir, options).emit()
}

interface FileCtx {
  imports: Set<number>
  /** Props of the component being emitted, by target view id. */
  props: Map<string, IRComponentProp[]>
  /** The component root id (its placement/size come from `className`). */
  rootId: string | null
  usesCx: boolean
  /** Enum variants: node path relative to the component root → prop → option → node. */
  variants: Map<string, Map<IRComponentProp & { type: "enum" }, Map<string, IRNode>>>
}

class ReactEmitter {
  private readonly vars: boolean
  private readonly split: boolean
  private readonly writer: CssWriter
  private readonly tokens: ThemeTokens
  private readonly attrOf: Map<string, string>
  private file!: FileCtx

  constructor(
    private readonly ir: IRDocument,
    private readonly o: ReactOptions,
  ) {
    this.vars = o.variables !== false
    this.split = o.components !== false
    this.writer = new CssWriter({
      variables: this.vars,
      onIssue: (code, message, nodeId) =>
        ir.issues.push({ code, message, ...(nodeId ? { nodeId } : {}) }),
    })
    const exposed = new Map<string, Set<string>>()
    for (const v of ir.variables) exposed.set(v.name, new Set(tailwindNamespaces(v)))
    this.tokens = (ns, ref) => (exposed.get(ref)?.has(ns) ? tailwindSuffix(ref) : null)
    this.attrOf = new Map(ir.axes.map((a) => [a.key, a.attr]))
  }

  emit(): ExportFile[] {
    const files: ExportFile[] = []
    const used = new NameSet()
    for (const root of this.ir.roots) {
      const name = used.take(pascal(root.name ?? root.key))
      files.push({ path: `${name}.tsx`, contents: this.page(name, root) })
    }
    if (this.split)
      for (const c of this.ir.components)
        if (c) files.push({ path: `${c.ident}.tsx`, contents: this.component(c) })
    const tokens = this.vars ? `${emitTokensCss(this.ir)}\n${emitTailwindTheme(this.ir)}` : null
    if (tokens) files.push({ path: "tokens.css", contents: tokens })
    return files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
  }

  // --- Classes ------------------------------------------------------------------------------

  private cls(decls: Decl[]): string {
    return utilities(decls, this.tokens).join(" ")
  }

  private css(node: IRNode): NodeCss {
    return this.writer.node(node)
  }

  /** `after:` utilities of a per-side stroke overlay. */
  private afterCls(after: Decl[] | null): string {
    if (!after) return ""
    return utilities(after, this.tokens)
      .map((u) => `after:${u}`)
      .join(" ")
  }

  private markup(): Markup {
    return new Markup(
      {
        writer: this.writer,
        icons: this.o.icons,
        layerNames: this.o.layerNames === true,
        ids: this.o.ids === true,
        styleAttrs: (node, css) => this.styleAttrs(node, css),
        runAttrs: (_node, _i, decls) => [["class", this.cls(decls)]],
        child: (node, build) => this.child(node, build),
        onIssue: (code, message, nodeId) =>
          this.ir.issues.push({ code, message, ...(nodeId ? { nodeId } : {}) }),
      },
      (k) => this.attrOf.get(k) ?? `data-${k}`,
    )
  }

  private styleAttrs(node: IRNode, css: NodeCss): [string, AttrValue][] {
    const f = this.file
    const after = this.afterCls(css.after)
    const isRoot = node.id === f.rootId
    if (isRoot) {
      // The root's placement and size come from the caller.
      const own = css.own.filter((d) => !SIZE_PROPS.has(d.prop))
      const size = css.own.filter((d) => SIZE_PROPS.has(d.prop))
      const base = [this.cls(own), after].filter(Boolean).join(" ")
      const variant = this.variantExpr(node, (n) => {
        const c = this.css(n)
        return [this.cls(c.own.filter((d) => !SIZE_PROPS.has(d.prop))), this.afterCls(c.after)]
          .filter(Boolean)
          .join(" ")
      })
      f.usesCx = true
      const def = JSON.stringify(this.cls([...css.placement, ...size]))
      return [["class", { expr: `cx(${variant ?? JSON.stringify(base)}, className ?? ${def})` }]]
    }
    const base = [this.cls([...css.placement, ...css.own]), after].filter(Boolean).join(" ")
    const variant = this.variantExpr(node, (n) => {
      const c = this.css(n)
      return [this.cls([...c.placement, ...c.own]), this.afterCls(c.after)]
        .filter(Boolean)
        .join(" ")
    })
    return [["class", variant ? { expr: variant } : base]]
  }

  /** `size ? { md: "…", sm: "…" }[size] : "…"` when an enum prop changes this node's classes. */
  private variantExpr(node: IRNode, classes: (n: IRNode) => string): string | null {
    const f = this.file
    if (f.rootId === null) return null
    const rel = relPath(f.rootId, node.id)
    const byProp = f.variants.get(rel)
    if (!byProp) return null
    let expr = JSON.stringify(classes(node))
    let changed = false
    for (const [prop, opts] of byProp) {
      const table: string[] = []
      let differs = false
      for (const [opt, n] of opts) {
        const c = classes(n)
        if (c !== classes(node)) differs = true
        table.push(`${JSON.stringify(opt)}: ${JSON.stringify(c)}`)
      }
      if (!differs) continue
      changed = true
      expr = `${prop.ident} ? ({ ${table.join(", ")} } as const)[${prop.ident}] : ${expr}`
    }
    return changed ? expr : null
  }

  // --- Children: instances and props ----------------------------------------------------------

  private child(node: IRNode, build: (n: IRNode) => Child | null): Child | null {
    const f = this.file
    // Declared props of the component being emitted.
    for (const p of f.props.get(node.id) ?? []) {
      switch (p.type) {
        case "boolean": {
          const inner = this.withoutProp(node, p, build)
          if (!inner) return null
          return { block: `{${p.ident} && (`, close: ")}", children: [inner] }
        }
        case "instance":
          return { expr: p.ident }
        default:
          break
      }
    }
    if (!node.visible) return null
    const ref = node.instance
    if (this.split && ref && !ref.needsInline && ref.component >= 0 && node.id !== f.rootId)
      return this.instance(node)
    return build(node)
  }

  /** Builds a node while ignoring one prop (avoids re-entering the conditional). */
  private withoutProp(
    node: IRNode,
    p: IRComponentProp,
    build: (n: IRNode) => Child | null,
  ): Child | null {
    const list = this.file.props.get(node.id) ?? []
    this.file.props.set(
      node.id,
      list.filter((x) => x !== p),
    )
    const vis = node.visible
    node.visible = true
    const out = this.child(node, build)
    node.visible = vis
    this.file.props.set(node.id, list)
    return out
  }

  /** `<Component className=… prop=… />` for an instance kept as a component reference. */
  private instance(node: IRNode): Child {
    const ref = node.instance as NonNullable<IRNode["instance"]>
    const comp = this.ir.components[ref.component] as IRComponent
    this.file.imports.add(ref.component)
    const css = this.css(node)
    const attrs: [string, AttrValue][] = [
      ["className", this.cls([...css.placement, ...css.own.filter((d) => SIZE_PROPS.has(d.prop))])],
    ]
    if (node.themeAttrs) {
      attrs.push(["data-kimo-theme", ""])
      for (const k of Object.keys(node.themeAttrs).sort())
        attrs.push([this.attrOf.get(k) ?? `data-${k}`, node.themeAttrs[k] as string])
    }
    if (this.o.ids) attrs.push(["data-kimo-id", node.id])
    const children: Child[] = []
    const slotProps = comp.props.filter((p) => p.type === "slot")
    for (const p of comp.props) {
      const a = ref.args[p.name]
      if (p.type === "slot") {
        const kids = ref.slots[p.name]
        if (!kids) continue
        const built = kids
          .map((k) => this.child(k, (n) => this.markup().build(n)))
          .filter((c): c is Child => !!c)
        if (slotProps.length === 1) children.push(...built)
        else attrs.push([p.ident, { expr: fragment(built) }])
        continue
      }
      if (!a) continue
      if (a.type === "text") attrs.push([p.ident, a.value])
      else if (a.type === "boolean") attrs.push([p.ident, { expr: String(a.value) }])
      else if (a.type === "enum") attrs.push([p.ident, a.value])
      else if (a.type === "instance") {
        const target = findById(node, `${node.id}/${relPath(comp.root.id, p.targetId)}`)
        if (target) {
          const built = this.child(target, (n) => this.markup().build(n))
          if (built) attrs.push([p.ident, { expr: fragment([built]) }])
        }
      }
    }
    return el(comp.ident, attrs, children)
  }

  // --- Files --------------------------------------------------------------------------------

  private newFile(rootId: string | null): FileCtx {
    return { imports: new Set(), props: new Map(), rootId, usesCx: false, variants: new Map() }
  }

  private importLines(self: number | null): string[] {
    return [...this.file.imports]
      .filter((i) => i !== self)
      .map((i) => (this.ir.components[i] as IRComponent).ident)
      .sort()
      .map((n) => `import { ${n} } from "./${n}"`)
  }

  private page(name: string, root: IRNode): string {
    this.file = this.newFile(null)
    const body = this.markup().build(root)
    const jsx = toJsx(body, 2)
    return [
      HEADER,
      ...this.importLines(null),
      ...(this.file.imports.size ? [""] : []),
      `export function ${name}() {`,
      "  return (",
      jsx,
      "  )",
      "}",
      "",
    ].join("\n")
  }

  private component(c: IRComponent): string {
    const index = this.ir.components.indexOf(c)
    this.file = this.newFile(c.root.id)
    for (const p of c.props) {
      const list = this.file.props.get(p.targetId) ?? []
      list.push(p)
      this.file.props.set(p.targetId, list)
      if (p.type === "enum") {
        for (const [opt, optNode] of Object.entries(p.options)) {
          // Index the option tree by path relative to its own root.
          const optRoot = optNode.id.slice(
            0,
            optNode.id.indexOf("/") < 0 ? undefined : optNode.id.indexOf("/"),
          )
          walk(optNode, (n) => {
            const rel = relPath(optRoot, n.id)
            let byProp = this.file.variants.get(rel)
            if (!byProp) {
              byProp = new Map()
              this.file.variants.set(rel, byProp)
            }
            let opts = byProp.get(p)
            if (!opts) {
              opts = new Map()
              byProp.set(p, opts)
            }
            opts.set(opt, n)
          })
        }
      }
    }
    const slotProps = c.props.filter((p) => p.type === "slot")
    const markup = this.markup()
    const build = markup.build.bind(markup)
    const rootEl = build(c.root)
    for (const p of c.props) {
      if (p.type !== "text") continue
      const t = markup.built.get(p.targetId)
      if (t) t.children = [{ expr: p.ident }]
    }
    // Slots: the frame keeps its classes; its children come from the prop (authored = default).
    for (const p of slotProps) {
      const ident = slotProps.length === 1 ? "children" : p.ident
      const slotEl = markup.built.get(p.targetId)
      if (slotEl) {
        const authored = slotEl.children
        slotEl.children = [{ expr: authored.length ? `${ident} ?? ${fragment(authored)}` : ident }]
      }
    }
    const fields: string[] = []
    const defaults: string[] = []
    for (const p of c.props) {
      const ident = p.type === "slot" && slotProps.length === 1 ? "children" : p.ident
      const doc = `  /** ${p.type} prop \`${p.name}\` */`
      switch (p.type) {
        case "text":
          fields.push(doc, `  ${ident}?: string`)
          defaults.push(`${ident} = ${JSON.stringify(p.default ?? textOf(c.root, p.targetId))}`)
          break
        case "boolean":
          fields.push(doc, `  ${ident}?: boolean`)
          defaults.push(`${ident} = ${p.default ?? visibleOf(c.root, p.targetId)}`)
          break
        case "enum":
          fields.push(
            doc,
            `  ${ident}?: ${
              Object.keys(p.options)
                .map((o) => JSON.stringify(o))
                .join(" | ") || "never"
            }`,
          )
          defaults.push(ident)
          break
        case "instance": {
          fields.push(doc, `  ${ident}?: ReactNode`)
          const target = findById(c.root, p.targetId)
          let def = "null"
          if (target) {
            const saved = this.file.props.get(p.targetId)
            this.file.props.delete(p.targetId)
            const built = this.child(target, build)
            if (saved) this.file.props.set(p.targetId, saved)
            if (built) def = fragment([built])
          }
          defaults.push(`${ident} = ${def}`)
          break
        }
        case "slot":
          fields.push(doc, `  ${ident}?: ReactNode`)
          defaults.push(ident)
          break
      }
    }
    fields.push("  className?: string")
    fields.push(DATA_ATTRIBUTES)
    defaults.push("className", "...rest")
    rootEl.attrs.push(["{...rest}", true])
    const needsNode = c.props.some((p) => p.type === "instance" || p.type === "slot")
    const lines: string[] = [HEADER]
    if (needsNode) lines.push('import type { ReactNode } from "react"')
    lines.push(...this.importLines(index), "")
    lines.push(
      'const cx = (...c: (string | false | null | undefined)[]) => c.filter(Boolean).join(" ")',
      "",
    )
    if (c.description) lines.push(`/** ${c.description.replace(/\*\//g, "*\\/")} */`)
    lines.push(`export interface ${c.ident}Props {`, ...fields, "}", "")
    lines.push(`export function ${c.ident}({ ${defaults.join(", ")} }: ${c.ident}Props) {`)
    lines.push("  return (", toJsx(rootEl, 2), "  )", "}", "")
    return lines.join("\n")
  }
}

// --- Helpers ----------------------------------------------------------------------------------

class NameSet {
  private used = new Set<string>()
  take(base: string): string {
    let n = base
    for (let i = 2; this.used.has(n); i++) n = `${base}${i}`
    this.used.add(n)
    return n
  }
}

function pascal(s: string): string {
  const out = kebab(s, "page")
    .split("-")
    .map((p) => (p[0]?.toUpperCase() ?? "") + p.slice(1))
    .join("")
  return /^[0-9]/.test(out) ? `P${out}` : out
}

function relPath(rootId: string, id: string): string {
  if (id === rootId) return ""
  return id.startsWith(`${rootId}/`) ? id.slice(rootId.length + 1) : id
}

function walk(n: IRNode, f: (n: IRNode) => void) {
  f(n)
  for (const c of n.children) walk(c, f)
}

function findById(n: IRNode, id: string): IRNode | null {
  if (n.id === id) return n
  for (const c of n.children) {
    const x = findById(c, id)
    if (x) return x
  }
  return null
}

function textOf(root: IRNode, id: string): string {
  return (
    findById(root, id)
      ?.text?.runs.map((r) => r.text)
      .join("") ?? ""
  )
}

function visibleOf(root: IRNode, id: string): boolean {
  return findById(root, id)?.visible ?? true
}

/** Children as a JSX expression (`<>…</>` for several). */
function fragment(children: Child[]): string {
  if (children.length === 0) return "null"
  if (children.length === 1 && isEl(children[0] as Child)) return toJsx(children[0] as Child, 0)
  return toJsx(el("", [], children), 0)
}
