/**
 * Design tokens from document variables (teardown §3.5, §9.2): W3C DTCG JSON, CSS custom
 * properties with multi-axis theme selectors, and a Tailwind v4 `@theme` block.
 *
 * Theme model in CSS (spec §10.4): `:root` holds every variable under the default theme. An
 * element that pins a theme carries `data-kimo-theme` plus one `data-<axis>` attribute per
 * axis with its full effective theme. On such elements every themed or aliasing variable is
 * reset to its fallback entry, then one zero-specificity rule per entry (`:where(…)`, in list
 * order) applies it where its `when` matches — so the last matching entry wins, partial
 * `when` works, and aliases are re-resolved under the element's theme.
 */
import { isObject, isRef, selectThemedValue, type Theme } from "@kimo/core-schema"
import { quoteFamily } from "../css/style"
import { cssColor, fmt, parseColor } from "../ir/color"
import { axisAttr, cssVarName, kebab } from "../ir/names"
import type { IRAxis, IRDocument, IRVariable } from "../ir/types"

/** Marker attribute of themed elements. */
export const THEME_MARKER = "data-kimo-theme"

const TAILWIND_NS: Record<string, string> = {
  color: "color",
  spacing: "spacing",
  radius: "radius",
  text: "text",
  font: "font",
  "font-weight": "font-weight",
  tracking: "tracking",
  leading: "leading",
  blur: "blur",
}

/** Tailwind theme key of a variable in a namespace: `--color-surface-card`. */
export function tailwindKey(ns: string, ref: string): string {
  return `--${ns}-${cssVarName(ref).slice(2)}`
}

/** Utility suffix of a token (`bg-<suffix>`). */
export function tailwindSuffix(ref: string): string {
  return cssVarName(ref).slice(2)
}

/** The Tailwind namespaces a variable is exposed under. */
export function tailwindNamespaces(v: IRVariable): string[] {
  const out = new Set<string>()
  for (const u of v.usage) if (TAILWIND_NS[u]) out.add(TAILWIND_NS[u] as string)
  if (out.size === 0) {
    if (v.type === "color") out.add("color")
    else if (v.type === "number" || v.type === "dimension") out.add("spacing")
  }
  return [...out].sort()
}

// --- CSS values -------------------------------------------------------------------------------

function cssValue(v: IRVariable, value: unknown): string | null {
  if (isRef(value)) return `var(${cssVarName(value.$ref)})`
  switch (v.type) {
    case "color":
      return cssColor(value)
    case "number":
      return typeof value === "number" ? fmt(value) : null
    case "dimension":
      return isObject(value) && typeof value.value === "number" ? fmt(value.value) : null
    case "string":
      if (typeof value !== "string") return null
      return v.usage.includes("font") ? quoteFamily(value) : JSON.stringify(value)
    case "boolean":
      return typeof value === "boolean" ? String(value) : null
    case "shadow": {
      const list = Array.isArray(value) ? value : [value]
      const parts = list.filter(isObject).map((s) => {
        const c = cssColor(s.color) ?? "transparent"
        const px = (x: unknown) => `${fmt(typeof x === "number" ? x : 0)}px`
        return `${s.inner === true ? "inset " : ""}${px(s.x)} ${px(s.y)} ${px(s.blur)} ${px(s.spread)} ${c}`
      })
      return parts.length ? parts.join(", ") : null
    }
    default:
      return null
  }
}

function selector(when: Record<string, string>, axes: Map<string, IRAxis>): string {
  return Object.keys(when)
    .sort()
    .map((k) => `[${axes.get(k)?.attr ?? axisAttr(k)}="${when[k]}"]`)
    .join("")
}

function defaultTheme(ir: IRDocument): Theme {
  const t: Theme = {}
  for (const a of ir.axes) t[a.key] = a.default
  return t
}

/** `tokens.css`: CSS custom properties with theme selectors. */
export function emitTokensCss(ir: IRDocument): string {
  const axes = new Map(ir.axes.map((a) => [a.key, a]))
  const theme = defaultTheme(ir)
  const lines: string[] = ["/* Generated by Kimo (@kimo/exporters). Do not edit. */", ""]
  const root: string[] = []
  const themed: string[] = []
  for (const v of ir.variables) {
    const name = v.css
    if (v.entries) {
      const sel = selectThemedValue(v.entries, (k) => theme[k])
      const value = cssValue(v, sel.value)
      if (value !== null) root.push(`  ${name}: ${value};`)
      const fallback =
        [...v.entries].reverse().find((e) => !e.when || Object.keys(e.when).length === 0) ??
        v.entries[0]
      const block: string[] = [`/* ${v.name} */`]
      const fb = fallback ? cssValue(v, fallback.value) : null
      if (fb !== null) block.push(`:where([${THEME_MARKER}]) { ${name}: ${fb}; }`)
      for (const e of v.entries) {
        if (!e.when || Object.keys(e.when).length === 0) continue
        const value = cssValue(v, e.value)
        if (value !== null) block.push(`:where(${selector(e.when, axes)}) { ${name}: ${value}; }`)
      }
      themed.push(block.join("\n"))
    } else {
      const value = cssValue(v, v.value)
      if (value === null) continue
      root.push(`  ${name}: ${value};`)
      // An alias re-resolves under each themed element.
      if (isRef(v.value))
        themed.push(`/* ${v.name} */\n:where([${THEME_MARKER}]) { ${name}: ${value}; }`)
    }
  }
  lines.push(":root {", ...root, "}")
  if (themed.length) lines.push("", ...themed.flatMap((b) => [b, ""]).slice(0, -1))
  return `${lines.join("\n")}\n`
}

/** Tailwind v4 `@theme inline` block mapping variables into theme namespaces. */
export function emitTailwindTheme(ir: IRDocument): string {
  const lines: string[] = ["@theme inline {"]
  for (const v of ir.variables)
    for (const ns of tailwindNamespaces(v))
      lines.push(`  ${tailwindKey(ns, v.name)}: ${themeValue(v, ns)};`)
  lines.push("}")
  return `${lines.join("\n")}\n`
}

/** The theme value of a variable in a namespace (a `var()` of its CSS custom property). */
function themeValue(v: IRVariable, ns: string): string {
  const ref = `var(${v.css})`
  return v.type === "number" || v.type === "dimension"
    ? ns === "font-weight" || ns === "leading"
      ? ref
      : `calc(${ref} * 1px)`
    : v.type === "string" && ns === "font"
      ? `${ref}, sans-serif`
      : ref
}

/** Tailwind v3 `theme` keys of the v4 namespaces. */
const TAILWIND_V3_KEY: Record<string, string> = {
  blur: "blur",
  color: "colors",
  font: "fontFamily",
  "font-weight": "fontWeight",
  leading: "lineHeight",
  radius: "borderRadius",
  spacing: "spacing",
  text: "fontSize",
  tracking: "letterSpacing",
}

/**
 * Tailwind v3 `tailwind.config.ts`: the same tokens as {@link emitTailwindTheme} under
 * `theme.extend` (utility names match: `bg-surface-base`), values reading `tokens.css`.
 */
export function emitTailwindConfig(ir: IRDocument): string {
  const groups = new Map<string, [string, string][]>()
  for (const v of ir.variables)
    for (const ns of tailwindNamespaces(v)) {
      const key = TAILWIND_V3_KEY[ns]
      if (!key) continue
      const list = groups.get(key) ?? []
      list.push([tailwindSuffix(v.name), themeValue(v, ns)])
      groups.set(key, list)
    }
  const lines = [
    "/* Generated by Kimo (@kimo/exporters). Do not edit. */",
    'import type { Config } from "tailwindcss"',
    "",
    "// Values read the CSS custom properties in tokens.css (import it in your global CSS).",
    "export default {",
    '  content: ["./**/*.{ts,tsx}"],',
    "  theme: {",
    "    extend: {",
  ]
  for (const key of [...groups.keys()].sort()) {
    lines.push(`      ${key}: {`)
    for (const [k, value] of groups.get(key) ?? [])
      lines.push(`        ${JSON.stringify(k)}: ${JSON.stringify(value)},`)
    lines.push("      },")
  }
  lines.push("    },", "  },", "} satisfies Config", "")
  return lines.join("\n")
}

// --- DTCG -------------------------------------------------------------------------------------

/** Token path of a variable: its `group` (dotted) then its name (split on `/`, `.`). */
export function tokenPath(v: Pick<IRVariable, "name" | "group">): string[] {
  const { name } = v
  const alias = name.includes(":") ? name.slice(0, name.indexOf(":")) : null
  const bare = alias ? name.slice(alias.length + 1) : name
  const nameParts = bare.split(/[/.]/).filter(Boolean)
  const groupParts = (v.group ?? "").split(".").filter(Boolean)
  // `group: "color.surface"` + `surface/card` → color.surface.card (no repeated segment).
  while (
    groupParts.length &&
    nameParts.length &&
    groupParts[groupParts.length - 1] === nameParts[0]
  )
    nameParts.shift()
  const path = [...groupParts, ...nameParts]
  return alias ? [alias, ...path] : path
}

function dtcgColor(value: unknown): unknown {
  if (typeof value === "string") {
    const c = parseColor(value)
    if (!c) return value
    const out: Record<string, unknown> = {
      colorSpace: "srgb",
      components: [c[0], c[1], c[2]].map((x) => Number(x.toFixed(4))),
      hex: value.length === 9 ? value.slice(0, 7).toLowerCase() : value.toLowerCase(),
    }
    if (c[3] < 1) out.alpha = Number(c[3].toFixed(4))
    return out
  }
  if (isObject(value) && value.space === "oklch")
    return withAlpha({ colorSpace: "oklch", components: [value.l, value.c, value.h] }, value.alpha)
  if (isObject(value) && value.space === "display-p3")
    return withAlpha(
      { colorSpace: "display-p3", components: [value.r, value.g, value.b] },
      value.alpha,
    )
  return value
}

function withAlpha(o: Record<string, unknown>, a: unknown) {
  if (typeof a === "number" && a < 1) o.alpha = a
  return o
}

/** W3C DTCG (2025.10) JSON of the document's variables, with Kimo theme extensions. */
export function emitDtcg(ir: IRDocument): string {
  const paths = new Map(ir.variables.map((v) => [v.name, tokenPath(v)]))
  const ref = (name: string) => `{${(paths.get(name) ?? [name]).join(".")}}`
  const val = (v: IRVariable, value: unknown): unknown => {
    if (isRef(value)) return ref(value.$ref)
    switch (v.type) {
      case "color":
        return dtcgColor(value)
      case "dimension":
        return value
      case "shadow": {
        const list = (Array.isArray(value) ? value : [value]).filter(isObject).map((s) => {
          const o: Record<string, unknown> = {
            color: dtcgColor(s.color),
            offsetX: { value: s.x, unit: "px" },
            offsetY: { value: s.y, unit: "px" },
            blur: { value: s.blur, unit: "px" },
            spread: { value: s.spread ?? 0, unit: "px" },
          }
          if (s.inner === true) o.inset = true
          return o
        })
        return list.length === 1 ? list[0] : list
      }
      case "typography": {
        if (!isObject(value)) return value
        const o: Record<string, unknown> = {}
        if (value.font !== undefined) o.fontFamily = value.font
        if (value.size !== undefined) o.fontSize = { value: value.size, unit: "px" }
        if (value.weight !== undefined) o.fontWeight = value.weight
        if (value.lineHeight !== undefined) o.lineHeight = value.lineHeight
        if (value.letterSpacing !== undefined)
          o.letterSpacing = { value: value.letterSpacing, unit: "px" }
        return o
      }
      default:
        return value
    }
  }
  const type = (v: IRVariable): string | null => {
    switch (v.type) {
      case "color":
      case "number":
      case "dimension":
      case "shadow":
      case "typography":
        return v.type
      case "string":
        return v.usage.includes("font") ? "fontFamily" : null
      default:
        return null
    }
  }
  const theme = defaultTheme(ir)
  const root: Record<string, unknown> = {
    $schema: "https://www.designtokens.org/schemas/2025.10/format.json",
  }
  if (ir.axes.length) {
    const axes: Record<string, unknown> = {}
    for (const a of ir.axes)
      axes[a.key] = { values: a.values, default: a.default, attribute: a.attr }
    root.$extensions = { "kimo.themes": { axes } }
  }
  for (const v of ir.variables) {
    const path = paths.get(v.name) as string[]
    let group = root
    for (const seg of path.slice(0, -1)) {
      const next = group[seg]
      if (isObject(next) && !("$value" in next)) group = next as Record<string, unknown>
      else {
        // A token and a group on one path: the token becomes the group's `$root` (DTCG 2025.10).
        const g: Record<string, unknown> = isObject(next) ? { $root: next } : {}
        group[seg] = g
        group = g
      }
    }
    const token: Record<string, unknown> = {}
    const t = type(v)
    if (t) token.$type = t
    if (v.entries) {
      const sel = selectThemedValue(v.entries, (k) => theme[k])
      token.$value = val(v, sel.value)
    } else token.$value = val(v, v.value)
    if (v.description) token.$description = v.description
    const ext: Record<string, unknown> = { "kimo.variable": v.name }
    if (!t) ext["kimo.type"] = v.type
    if (v.entries)
      ext["kimo.themes"] = v.entries.map((e) =>
        e.when && Object.keys(e.when).length
          ? { when: e.when, value: val(v, e.value) }
          : { value: val(v, e.value) },
      )
    token.$extensions = ext
    const last = path[path.length - 1] as string
    const existing = group[last]
    if (isObject(existing) && !("$value" in existing)) existing.$root = token
    else group[last] = token
  }
  return `${JSON.stringify(root, null, 2)}\n`
}

/** File-name-safe stem of the document name. */
export function stem(ir: IRDocument): string {
  return kebab(ir.name, "export")
}
