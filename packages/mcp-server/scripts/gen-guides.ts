/**
 * Builds the agent guides behind `kimo_read_docs` (ADR 0013 §2, §12 item 5):
 *
 *   packages/mcp-server/guides/<path>.md   (source, MIT, one file per DOC_PATHS entry)
 *     → packages/mcp-server/generated/guides.ts  (embedded strings: browser-safe, no fs at
 *                                                runtime; re-exported by src/guides.ts)
 *     → docs/agents/<path>.md              (human-facing copy, same text plus a header)
 *
 * `bun scripts/gen-guides.ts` writes; `--check` exits 1 when an output is stale (CI runs the
 * same comparison from test/guides.test.ts).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { DOC_PATHS } from "../src/tools/session"

const PKG = resolve(import.meta.dir, "..")
const REPO = resolve(PKG, "../..")
export const GUIDES_DIR = join(PKG, "guides")
export const MODULE_PATH = join(PKG, "generated", "guides.ts")
export const DOCS_DIR = join(REPO, "docs", "agents")

export interface GuideSource {
  path: string
  title: string
  related: string[]
  markdown: string
}

export function readSources(): GuideSource[] {
  return DOC_PATHS.map((path) => {
    const file = join(GUIDES_DIR, `${path}.md`)
    const raw = readFileSync(file, "utf8")
    const m = /^<!-- related: ([^>]*) -->\n/.exec(raw)
    const related = m
      ? (m[1] as string)
          .split(",")
          .map((s) => s.trim())
          .filter(Boolean)
      : []
    const markdown = m ? raw.slice(m[0].length) : raw
    const title = /^# (.+)$/m.exec(markdown)?.[1] ?? path
    return { path, title, related, markdown }
  })
}

export function renderModule(sources: GuideSource[]): string {
  const entries = sources
    .map(
      (s) =>
        `  ${JSON.stringify(s.path)}: {\n    title: ${JSON.stringify(s.title)},\n    related: ${JSON.stringify(s.related)},\n    markdown: ${JSON.stringify(s.markdown)},\n  },`,
    )
    .join("\n")
  return `/**
 * GENERATED by scripts/gen-guides.ts from packages/mcp-server/guides/*.md. Do not edit by hand.
 *
 * The MIT agent guides served by \`kimo_read_docs\` and the resources \`kimo://docs/{path}\`
 * (ADR 0013 §2). Embedded as strings so the main entry stays free of Node imports.
 */
import type { DOC_PATHS } from "../src/tools/session"

export type GuidePath = (typeof DOC_PATHS)[number]

export interface Guide {
  title: string
  /** Guides worth reading next. */
  related: GuidePath[]
  markdown: string
}

export const GUIDES: Record<GuidePath, Guide> = {
${entries}
}

/** The guide for \`path\` (the index when omitted), or null for an unknown path. */
export function readGuide(path?: string): ({ path: GuidePath } & Guide) | null {
  const p = (path ?? "index") as GuidePath
  const g = Object.hasOwn(GUIDES, p) ? GUIDES[p] : undefined
  return g ? { path: p, ...g } : null
}

/** \`kimo://docs/{path}\` → guide path, or null. */
export function guidePathFromUri(uri: string): GuidePath | null {
  const m = /^kimo:\\/\\/docs\\/(.+)$/.exec(uri)
  const p = m?.[1] ?? null
  return p !== null && Object.hasOwn(GUIDES, p) ? (p as GuidePath) : null
}
`
}

export function renderDoc(s: GuideSource): string {
  return `<!-- Generated from packages/mcp-server/guides/${s.path}.md by scripts/gen-guides.ts. Agents read the same text with kimo_read_docs {path: "${s.path}"}. MIT licence. -->\n\n${s.markdown}`
}

export function outputs(): { path: string; text: string }[] {
  const sources = readSources()
  return [
    { path: MODULE_PATH, text: renderModule(sources) },
    ...sources.map((s) => ({ path: join(DOCS_DIR, `${s.path}.md`), text: renderDoc(s) })),
  ]
}

if (import.meta.main) {
  const check = process.argv.includes("--check")
  let stale = 0
  for (const o of outputs()) {
    const cur = existsSync(o.path) ? readFileSync(o.path, "utf8") : null
    if (cur === o.text) continue
    if (check) {
      console.error(`stale: ${o.path}`)
      stale++
    } else {
      mkdirSync(dirname(o.path), { recursive: true })
      writeFileSync(o.path, o.text)
      console.log(`wrote ${o.path}`)
    }
  }
  if (stale) {
    console.error("run: bun packages/mcp-server/scripts/gen-guides.ts")
    process.exit(1)
  }
}
