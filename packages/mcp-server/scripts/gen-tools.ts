/**
 * Writes `generated/tools.json`: the `tools/list` payload (desktop host, no stubs) plus the
 * socket protocol version. The Rust `kimo-mcp` shim embeds it (`include_str!`) so it can answer
 * `initialize` and `tools/list` while the app is not running and fail calls with
 * APP_NOT_RUNNING (ADR 0013 §7). `--check` fails when the file is stale (CI).
 */
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { listTools, SOCKET_PROTOCOL, toMcpDescriptor } from "../src/index"

const out = join(import.meta.dir, "..", "generated", "tools.json")
const payload = {
  $comment: "Generated by packages/mcp-server/scripts/gen-tools.ts. Do not edit.",
  socketProtocol: SOCKET_PROTOCOL,
  tools: listTools({ host: "desktop" }).map(toMcpDescriptor),
}
const text = `${JSON.stringify(payload, null, 2)}\n`
if (process.argv.includes("--check")) {
  let current = ""
  try {
    current = readFileSync(out, "utf8")
  } catch {}
  if (current !== text) {
    console.error("generated/tools.json is stale: run `bun run gen:tools` in packages/mcp-server")
    process.exit(1)
  }
} else writeFileSync(out, text)
